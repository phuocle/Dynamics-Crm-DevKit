    internal static class DevOpsLinkBuilder
    {
        public static string BuildWorkItemUrl(string devOps, string org, string project, string id)
        {
            if (string.IsNullOrWhiteSpace(devOps))
                return null;

            switch (devOps.Trim().ToLowerInvariant())
            {
                case "azuredevops":
                    var encodedProject = Uri.EscapeDataString(project ?? string.Empty);
                    return $"https://dev.azure.com/{org}/{encodedProject}/_workitems/edit/{id}";

                case "github":
                    return $"https://github.com/{org}/{project}/issues/{id}";

                case "jira":
                    return $"https://{org}.atlassian.net/browse/{id}";

                case "custom":
                    if (string.IsNullOrWhiteSpace(org)) return null;
                    if (org.IndexOf("{id}", StringComparison.OrdinalIgnoreCase) >= 0)
                        return org.Replace("{id}", id);
                    return org.TrimEnd('/') + "/" + id;

                default:
                    return null;
            }
        }
    }

    internal class TaskDocumentCodeGenerator
    {
        private const string AttributeShortName = "DocumentMethodAttribute";
        private const string FooterPrefix = ">This file generated by tool";

        private static readonly Dictionary<string, string> StageEnumMap = Enum.GetValues(typeof(DocumentMethodStage))
            .Cast<DocumentMethodStage>()
            .ToDictionary(e => ((int)e).ToString(), e => e.ToString());

        private static readonly Dictionary<string, string> MessageEnumMap = Enum.GetValues(typeof(DocumentMethodMessage))
            .Cast<DocumentMethodMessage>()
            .ToDictionary(e => ((int)e).ToString(), e => e.ToString());

        internal static void Run(string folder, string output, string devOps, string org, string project)
        {
            if (!Path.IsPathRooted(output))
                output = Path.GetFullPath(output);

            if (!Directory.Exists(folder))
                throw new DirectoryNotFoundException($"Folder not found: {folder}");

            Directory.CreateDirectory(output);

            AnsiConsole.MarkupLine($"[cyan]Folder:[/] {Markup.Escape(folder)}");
            AnsiConsole.MarkupLine($"[cyan]Output:[/] {Markup.Escape(output)}");

            if (!string.IsNullOrWhiteSpace(devOps))
                AnsiConsole.MarkupLine($"[cyan]DevOps:[/] {Markup.Escape(devOps)} (Org: {Markup.Escape(org ?? "")}, Project: {Markup.Escape(project ?? "")})");
            else
                AnsiConsole.MarkupLine("[dim]DevOps link: disabled (WI shown as plain text)[/]");

            var dllFiles = Directory.GetFiles(folder, "*.dll", SearchOption.TopDirectoryOnly);
            var resolver = new DefaultAssemblyResolver();
            resolver.AddSearchDirectory(folder);

            var generated = 0;
            foreach (var dll in dllFiles)
            {
                var fileName = Path.GetFileName(dll) ?? "assembly";
                var outFile = Path.Combine(output, Path.GetFileNameWithoutExtension(fileName) + ".md");
                var outputDir = Path.GetDirectoryName(outFile) ?? output;

                try
                {
                    using (var module = ModuleDefinition.ReadModule(dll, new ReaderParameters { AssemblyResolver = resolver }))
                    {
                        var content = GenerateMarkdownForModule(module, fileName, devOps, org, project, outputDir);
                        if (!string.IsNullOrEmpty(content))
                        {
                            if (!File.Exists(outFile) || ContentChangedIgnoringFooter(outFile, content))
                            {
                                File.WriteAllText(outFile, content, Encoding.UTF8);
                            }
                            AnsiConsole.MarkupLine($"  [dim]Generated:[/] {Path.GetFileName(outFile)}");
                            generated++;
                        }
                    }
                }
                catch (Exception ex)
                {
                    var content = GenerateErrorMarkdown(fileName, ex);
                    File.WriteAllText(outFile, content, Encoding.UTF8);
                    AnsiConsole.MarkupLine($"  [red]Error:[/] {Markup.Escape(fileName)} - {Markup.Escape(ex.Message)}");
                }
            }
            AnsiConsole.MarkupLine($"[green]Done![/] {generated} file(s) generated. Output: {Markup.Escape(output)}");
        }

        private static string GenerateMarkdownForModule(ModuleDefinition module, string fileName, string devOps, string org, string project, string outputDirectory)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Document Methods");
            sb.AppendLine($">Assembly: `{fileName}`");
            sb.AppendLine();

            var rows = new List<Row>();
            var assemblyRootName = module.Assembly.Name.Name;
            var codeRootDir = FindSiblingProjectRoot(outputDirectory, assemblyRootName);

            foreach (var type in module.Types)
            {
                if (type.Name == "<Module>") continue;
                ProcessType(type, rows);
                foreach (var nested in type.NestedTypes)
                    ProcessType(nested, rows);
            }

            if (rows.Count == 0)
                return null;

            var groups = rows
                .OrderBy(r => r.TypeFullName)
                .ThenBy(r => r.MethodName)
                .GroupBy(r => r.TypeFullName)
                .ToList();

            sb.AppendLine($"> **{rows.Count}** methods across **{groups.Count}** classes");
            sb.AppendLine();

            sb.AppendLine("## Table of Contents");
            foreach (var classGroup in groups)
            {
                var display = classGroup.Key;
                var anchor = display.Replace(".", "").ToLower();
                sb.AppendLine($"<details><summary><b>{display}</b></summary>");
                sb.AppendLine();
                foreach (var r in classGroup
                    .OrderBy(x => GetWiSortKey(x.WI))
                    .ThenBy(x => x.MethodName, StringComparer.OrdinalIgnoreCase))
                {
                    sb.AppendLine($"- [{r.MethodName}](#{anchor})");
                }
                sb.AppendLine("</details>");
            }
            sb.AppendLine();

            foreach (var group in groups)
            {
                var display = group.Key;
                var anchor = display.Replace(".", "").ToLower();
                sb.AppendLine($"<a id=\"{anchor}\"></a>");
                sb.AppendLine();
                var sourceLink = BuildSourceLink(assemblyRootName, display, codeRootDir, outputDirectory);
                if (!string.IsNullOrEmpty(sourceLink))
                    sb.AppendLine($"## [{display}]({sourceLink})");
                else
                    sb.AppendLine($"## {display}");

                var entityTag = group.Select(r => r.Entity).FirstOrDefault(e => !string.IsNullOrEmpty(e));
                if (!string.IsNullOrEmpty(entityTag))
                    sb.AppendLine($"> Target Entity: `{entityTag}`");

                sb.AppendLine();
                sb.AppendLine("| **Method** | **Stage** | **Message** | **WI** | **Fields** | **Description** |");
                sb.AppendLine("|:-|:-|:-|:-|:-|:-|");

                foreach (var r in group
                    .OrderBy(x => GetWiSortKey(x.WI))
                    .ThenBy(x => x.MethodName, StringComparer.OrdinalIgnoreCase))
                {
                    var wiCell = FormatWi(r.WI, devOps, org, project);
                    var desc = EscapePipes(r.Description);
                    var fieldsCell = FormatFields(r.Fields);
                    sb.AppendLine($"| `{r.MethodName}` | `{r.Stage}` | `{r.Message}` | {wiCell} | {fieldsCell} | {desc} |");
                }
                sb.AppendLine();
            }

            AppendFooter(sb);
            return sb.ToString();
        }

        private static void ProcessType(TypeDefinition type, List<Row> rows)
        {
            foreach (var method in type.Methods)
            {
                try
                {
                    foreach (var attr in method.CustomAttributes)
                    {
                        if (!string.Equals(attr.AttributeType.Name, AttributeShortName, StringComparison.Ordinal))
                            continue;

                        string wi = string.Empty, desc = string.Empty, stage = string.Empty;
                        string message = string.Empty, fields = string.Empty, entity = string.Empty;

                        var ctorArgs = attr.ConstructorArguments;
                        if (ctorArgs != null && ctorArgs.Count >= 6)
                        {
                            wi = CecilArgToString(ctorArgs[0]);
                            desc = CecilArgToString(ctorArgs[1]);
                            stage = CecilEnumToName(ctorArgs[2], StageEnumMap);
                            entity = CecilArgToString(ctorArgs[3]);
                            message = CecilEnumToName(ctorArgs[4], MessageEnumMap);
                            fields = CecilArgToString(ctorArgs[5]);
                        }

                        if (attr.HasProperties)
                        {
                            foreach (var prop in attr.Properties)
                            {
                                var name = prop.Name;
                                if (string.Equals(name, "WI", StringComparison.OrdinalIgnoreCase)) wi = CecilArgToString(prop.Argument);
                                else if (string.Equals(name, "Description", StringComparison.OrdinalIgnoreCase)) desc = CecilArgToString(prop.Argument);
                                else if (string.Equals(name, "Fields", StringComparison.OrdinalIgnoreCase)) fields = CecilArgToString(prop.Argument);
                                else if (string.Equals(name, "Stage", StringComparison.OrdinalIgnoreCase)) stage = CecilEnumToName(prop.Argument, StageEnumMap);
                                else if (string.Equals(name, "Message", StringComparison.OrdinalIgnoreCase)) message = CecilEnumToName(prop.Argument, MessageEnumMap);
                                else if (string.Equals(name, "Entity", StringComparison.OrdinalIgnoreCase)) entity = CecilArgToString(prop.Argument);
                            }
                        }

                        rows.Add(new Row
                        {
                            TypeFullName = type.FullName.Replace("/", "."),
                            MethodName = method.Name,
                            Stage = stage,
                            Message = message,
                            WI = wi,
                            Fields = fields,
                            Description = desc,
                            Entity = entity
                        });
                    }
                }
                catch { }
            }
        }

        private static string CecilArgToString(CustomAttributeArgument arg)
        {
            return arg.Value?.ToString() ?? string.Empty;
        }

        private static string CecilEnumToName(CustomAttributeArgument arg, Dictionary<string, string> enumMap)
        {
            var raw = arg.Value?.ToString() ?? string.Empty;
            string mapped;
            if (enumMap.TryGetValue(raw, out mapped))
                return mapped;
            return raw;
        }

        private static bool ContentChangedIgnoringFooter(string existingPath, string newContent)
        {
            try
            {
                if (!File.Exists(existingPath)) return true;
                var oldLines = File.ReadAllLines(existingPath);
                var newLines = SplitLines(newContent);
                var oldCore = GetCoreContentForCompare(oldLines);
                var newCore = GetCoreContentForCompare(newLines);
                return !string.Equals(oldCore, newCore, StringComparison.Ordinal);
            }
            catch
            {
                return true;
            }
        }

        private static string GetCoreContentForCompare(string[] lines)
        {
            if (lines == null || lines.Length == 0) return string.Empty;
            int end = lines.Length - 1;
            while (end >= 0 && string.IsNullOrWhiteSpace(lines[end])) end--;
            if (end < 0) return string.Empty;
            while (end >= 0 && (
                lines[end].StartsWith(FooterPrefix, StringComparison.Ordinal) ||
                lines[end].StartsWith(">***This file modified on:", StringComparison.Ordinal) ||
                lines[end].StartsWith(">Generated by tool", StringComparison.Ordinal) ||
                lines[end].TrimStart() == "---"))
            {
                end--;
                while (end >= 0 && string.IsNullOrWhiteSpace(lines[end])) end--;
            }
            return string.Join("\n", lines.Take(end + 1));
        }

        private static string[] SplitLines(string text)
        {
            return text?.Split(new[] { "\r\n", "\n", "\r" }, StringSplitOptions.None) ?? new string[0];
        }

        private static string BuildSourceLink(string assemblyRootName, string typeFullName, string codeRootDir, string outputDirectory)
        {
            try
            {
                if (string.IsNullOrEmpty(assemblyRootName) || string.IsNullOrEmpty(typeFullName)) return string.Empty;

                string rest = null;
                if (typeFullName.StartsWith(assemblyRootName + ".", StringComparison.Ordinal))
                {
                    rest = typeFullName.Substring(assemblyRootName.Length + 1);
                }
                else
                {
                    var nsPrefix = Regex.Replace(assemblyRootName, @"\.(\d)", "._$1");
                    if (typeFullName.StartsWith(nsPrefix + ".", StringComparison.Ordinal))
                        rest = typeFullName.Substring(nsPrefix.Length + 1);
                }
                if (rest == null) rest = typeFullName;

                var parts = rest.Split('.');
                if (parts.Length == 0) return string.Empty;
                var csFileName = parts[parts.Length - 1] + ".cs";
                var subDirs = parts.Take(parts.Length - 1).ToArray();
                var targetFullPath = Path.Combine(codeRootDir, Path.Combine(subDirs.Length > 0 ? Path.Combine(subDirs) : string.Empty), csFileName);

                var relative = MakeRelativePath(AppendDirectorySeparator(outputDirectory), targetFullPath);
                return relative.Replace("\\", "/");
            }
            catch
            {
                return string.Empty;
            }
        }

        private static string FindSiblingProjectRoot(string startingDir, string projectFolderName)
        {
            try
            {
                var dir = new DirectoryInfo(startingDir);
                while (dir != null && dir.Parent != null)
                {
                    var sibling = Path.Combine(dir.Parent.FullName, projectFolderName);
                    if (Directory.Exists(sibling))
                        return sibling;
                    dir = dir.Parent;
                }
            }
            catch { }
            var parent = Directory.GetParent(startingDir);
            return parent == null ? projectFolderName : Path.Combine(parent.FullName, projectFolderName);
        }

        private static string MakeRelativePath(string fromDirectory, string toPath)
        {
            try
            {
                var fromUri = new Uri(AppendDirectorySeparator(fromDirectory));
                var toUri = new Uri(toPath);
                var relativeUri = fromUri.MakeRelativeUri(toUri);
                var relativePath = Uri.UnescapeDataString(relativeUri.ToString());
                return relativePath.Replace('/', Path.DirectorySeparatorChar);
            }
            catch
            {
                return toPath;
            }
        }

        private static string AppendDirectorySeparator(string path)
        {
            if (string.IsNullOrEmpty(path)) return path;
            if (!path.EndsWith(Path.DirectorySeparatorChar.ToString()))
                return path + Path.DirectorySeparatorChar;
            return path;
        }

        private static int GetWiSortKey(string wi)
        {
            if (string.IsNullOrWhiteSpace(wi)) return int.MaxValue;
            int min = int.MaxValue;
            foreach (var t in wi.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries).Select(s => s.Trim()))
            {
                int n;
                if (int.TryParse(t, out n) && n < min) min = n;
            }
            return min;
        }

        private static string FormatWi(string wi, string devOps, string org, string project)
        {
            if (string.IsNullOrWhiteSpace(wi)) return string.Empty;
            var ordered = wi.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(s => s.Trim())
                .Where(s => !string.IsNullOrEmpty(s))
                .Select(id => { int num; return new { Raw = id, Num = int.TryParse(id, out num) ? (int?)num : null }; })
                .OrderBy(x => x.Num ?? int.MaxValue)
                .ThenBy(x => x.Raw, StringComparer.OrdinalIgnoreCase)
                .Select(x => x.Raw);

            var parts = new List<string>();
            foreach (var id in ordered)
            {
                var url = DevOpsLinkBuilder.BuildWorkItemUrl(devOps, org, project, id);
                if (!string.IsNullOrEmpty(url))
                    parts.Add($"[{EscapePipes(id)}]({url})");
                else
                    parts.Add(EscapePipes(id));
            }
            return string.Join(", ", parts);
        }

        private static string FormatFields(string fields)
        {
            if (string.IsNullOrWhiteSpace(fields)) return string.Empty;
            var joined = string.Join(", ", fields
                .Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(s => s.Trim())
                .Where(s => !string.IsNullOrEmpty(s))
                .Select(EscapePipes)
                .Select(s => $"`{s}`"));
            return string.IsNullOrEmpty(joined) ? string.Empty : joined;
        }

        private static void AppendFooter(StringBuilder sb)
        {
            sb.AppendLine("---");
            sb.Append(">This file generated by tool ***");
            sb.Append(Assembly.GetExecutingAssembly().GetName().Name);
            sb.AppendLine(".DocumentCodeGenerator***");
            sb.AppendLine("---");
            sb.Append(">***This file modified on:*** ");
            sb.AppendLine($"```{DateTime.Now:yyyy-MMM-dd HH:mm:ss}```");
        }

        private static string GenerateErrorMarkdown(string fileName, Exception ex)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Document Methods");
            sb.AppendLine($">Assembly: `{fileName}`");
            sb.AppendLine();
            sb.AppendLine("> Error while loading or scanning assembly.");
            sb.AppendLine();
            sb.AppendLine("```");
            sb.AppendLine(ex.ToString());
            sb.AppendLine("```");
            sb.AppendLine();
            AppendFooter(sb);
            return sb.ToString();
        }

        private static string EscapePipes(string input)
        {
            if (string.IsNullOrEmpty(input)) return string.Empty;
            return input.Replace("|", "\\|");
        }

        private class Row
        {
            public string TypeFullName { get; set; }
            public string MethodName { get; set; }
            public string Stage { get; set; }
            public string Message { get; set; }
            public string WI { get; set; }
            public string Fields { get; set; }
            public string Description { get; set; }
            public string Entity { get; set; }
        }
    }
